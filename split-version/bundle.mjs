import { readFile, writeFile } from 'node:fs/promises';

// common.glsl is prepended by Shader Studio and blazer-preview.html.
// Each Image-pass dependency must precede every function that uses it.
const sources = [
  'hair_sdf.glsl',
  'body_clothing_sdf.glsl',
  'face_sdf.glsl',
  'raymarching.glsl',
  'lighting_shading.glsl',
  'studio_background.glsl',
  'main_image.glsl',
];
const outputName = 'selfie_modifyAndStudy.glsl';
const localFile = name => new URL(name, import.meta.url);
const args = process.argv.slice(2);

try {
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw new Error('Usage: node bundle.mjs [--check]');
  }
  await readFile(localFile('common.glsl'), 'utf8');
  const sections = await Promise.all(sources.map(async name => {
    const source = (await readFile(localFile(name), 'utf8')).replace(/\r\n?/g, '\n');
    return `// ---- ${name} ----\n${source}${source.endsWith('\n') ? '' : '\n'}`;
  }));
  const bundled = '// Generated by bundle.mjs; edit the split sources, then regenerate.\n'
    + '// Requires common.glsl, supplied by the .sha.json common pass or the HTML preview.\n'
    + '// Original source attribution and copyright notice are preserved in common.glsl.\n\n'
    + sections.join('\n');

  if (args[0] === '--check') {
    const existing = await readFile(localFile(outputName), 'utf8');
    if (existing !== bundled) throw new Error(`${outputName} is stale. Run node bundle.mjs.`);
    console.log(`${outputName} is up to date.`);
  } else {
    await writeFile(localFile(outputName), bundled, 'utf8');
    console.log(`Generated ${outputName} from ${sources.length} Image-pass modules.`);
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
